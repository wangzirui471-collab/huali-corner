import assert from 'node:assert/strict';
const disk=new Map();
globalThis.window={HUALI_STATIC_DEMO:false};
globalThis.sessionStorage={getItem:()=>null,removeItem(){}};
globalThis.localStorage={getItem:key=>disk.get(key)||null,setItem:(key,value)=>disk.set(key,value),removeItem:key=>disk.delete(key),key:i=>[...disk.keys()][i],get length(){return disk.size;}};
globalThis.document={querySelector:()=>null,querySelectorAll:()=>[]};
globalThis.location={hash:'#me'};
const {state}=await import('../web 7M/src/core/state.js');
const {clicks}=await import('../web 7M/src/actions/account.js');
let resolve,started;
const entered=new Promise(done=>started=done);
let requests=0;
globalThis.fetch=async()=>{requests++;started();return new Promise(done=>resolve=done);};
state.me={id:1};state.token='session-A';
const old=clicks.logout();await entered;
const duplicate=clicks.logout();
await Promise.resolve();
assert.equal(requests,1,'same-session logout must be single-flight');
state.me={id:2};state.token='session-B';disk.set('zj-draft-2','new private draft');
resolve({ok:true,json:async()=>({ok:true})});
await Promise.allSettled([old,duplicate]);
assert.equal(state.me?.id,2,'late A logout must not log B out');
assert.equal(state.token,'session-B');assert.equal(disk.get('zj-draft-2'),'new private draft');
console.log('Duplicate and late logout preserve a newly active account and its drafts.');
